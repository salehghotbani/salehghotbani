import io
import json
from pathlib import Path
import sys
import tarfile
import unittest
from unittest.mock import patch
from urllib.error import HTTPError

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
from source_lines import count_archive, repository_lines


def archive(files):
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode='w:gz') as output:
        for path, content in files.items():
            data = content.encode() if isinstance(content, str) else content
            member = tarfile.TarInfo('repo-root/' + path)
            member.size = len(data)
            output.addfile(member, io.BytesIO(data))
        link = tarfile.TarInfo('repo-root/linked.py')
        link.type = tarfile.SYMTYPE
        link.linkname = '/outside/source.py'
        output.addfile(link)
    buffer.seek(0)
    return buffer


class SourceLineTests(unittest.TestCase):
    def test_source_exclusions_and_physical_lines(self):
        files = {
            'src/main.py': '# comment\n\nprint(1)\r\n  \nprint(2)',
            'src/view.tsx': 'export function View() {\nreturn <div/>;\n}\n',
            'node_modules/dep/index.js': 'should not count\n',
            'nested/vendor/dep.py': 'should not count\n',
            'dist/site.html': '<html>generated</html>',
            'src/types.d.ts': 'declare const x: string;',
            'assets/app.min.js': 'minified',
            'src/service_pb2.py': 'generated',
            'src/generated.cs': '// <auto-generated/>\nclass Generated {}',
            'README.md': 'not source',
            'binary.c': b'\x00\x01\n',
        }
        self.assertEqual(count_archive(archive(files)), {'Python': 3, 'TypeScript': 3})

    def test_notebook_counts_only_code_cells_in_declared_language(self):
        notebook = {
            'metadata': {'language_info': {'name': 'python'}},
            'cells': [
                {'cell_type': 'markdown', 'source': ['Some prose\n']},
                {'cell_type': 'code', 'source': ['# comment\n', '\n', 'print(1)\n'], 'outputs': [{'text': ['output\n' * 100]}]},
                {'cell_type': 'code', 'source': 'x = 1\n\ny = 2'},
            ],
        }
        self.assertEqual(count_archive(archive({'lesson.ipynb': json.dumps(notebook)})), {'Python': 4})

    def test_stream_prefix_multibyte_and_utf16(self):
        files = {'src/main.py': 'a' * 4095 + 'é\n\nprint(1)', 'src/demo.cs': 'class X {}\n\n// comment'.encode('utf-16')}
        self.assertEqual(count_archive(archive(files)), {'Python': 2, 'C#': 2})

    def test_invalid_notebook_fails_instead_of_publishing_partial_counts(self):
        with self.assertRaises(ValueError):
            count_archive(archive({'src/main.py': 'print(1)', 'lesson.ipynb': '{bad json'}))

    def test_zero_size_metadata_does_not_skip_small_sources(self):
        with patch('source_lines.urlopen', return_value=archive({'tiny.py': 'x = 1'})):
            self.assertEqual(repository_lines('owner', {'name': 'tiny', 'default_branch': 'main', 'size': 0}, ''), {'Python': 1})

    def test_empty_repository_needs_explicit_empty_tree_response(self):
        errors = [HTTPError('withheld', 404, 'Not found', {}, None), HTTPError('withheld', 409, 'Empty repository', {}, None)]
        with patch('source_lines.urlopen', side_effect=errors):
            self.assertEqual(repository_lines('owner', {'name': 'empty', 'default_branch': 'main', 'size': 0}, ''), {})


if __name__ == '__main__':
    unittest.main()
