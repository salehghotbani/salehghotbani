"""Count non-empty physical source lines, including comments, with no dependencies.

Archives are streamed without extracting or retaining source files. Notebook outputs
and markdown are ignored; code cells are attributed to their declared language.
"""

from collections import Counter
import io
import json
from pathlib import PurePosixPath
import tarfile
from urllib.parse import quote
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen


EXTENSIONS = {
    '.py': 'Python', '.pyw': 'Python', '.pyi': 'Python',
    '.js': 'JavaScript', '.jsx': 'JavaScript', '.mjs': 'JavaScript', '.cjs': 'JavaScript',
    '.ts': 'TypeScript', '.tsx': 'TypeScript', '.mts': 'TypeScript', '.cts': 'TypeScript',
    '.java': 'Java', '.kt': 'Kotlin', '.kts': 'Kotlin', '.scala': 'Scala',
    '.c': 'C', '.h': 'C', '.cc': 'C++', '.cpp': 'C++', '.cxx': 'C++', '.hpp': 'C++', '.hh': 'C++',
    '.cs': 'C#', '.rs': 'Rust', '.go': 'Go', '.swift': 'Swift', '.dart': 'Dart',
    '.gd': 'GDScript', '.html': 'HTML', '.htm': 'HTML', '.css': 'CSS', '.scss': 'SCSS', '.sass': 'Sass',
    '.vue': 'Vue', '.svelte': 'Svelte', '.mako': 'Mako', '.php': 'PHP', '.rb': 'Ruby',
    '.sh': 'Shell', '.bash': 'Shell', '.zsh': 'Shell', '.ps1': 'PowerShell', '.psm1': 'PowerShell',
    '.tex': 'TeX', '.sty': 'TeX', '.cmake': 'CMake', '.sql': 'SQL', '.r': 'R', '.jl': 'Julia',
    '.lua': 'Lua', '.pl': 'Perl', '.ex': 'Elixir', '.exs': 'Elixir', '.erl': 'Erlang', '.hs': 'Haskell',
}
EXCLUDED_DIRS = {
    '.git', 'node_modules', 'vendor', 'third_party', 'third-party', 'site-packages',
    '.venv', 'venv', 'env', '__pycache__', '.ipynb_checkpoints', 'dist', 'build',
    'out', 'coverage', '.next', '.nuxt', '.gradle', '.idea', 'target', 'bin', 'obj',
}
NOTEBOOK_LANGUAGES = {
    'python': 'Python', 'python3': 'Python', 'julia': 'Julia', 'r': 'R',
    'javascript': 'JavaScript', 'typescript': 'TypeScript', 'scala': 'Scala',
    'bash': 'Shell', 'c++': 'C++', 'c': 'C', 'java': 'Java',
}


def classify(path):
    path = PurePosixPath(path)
    if any(part.lower() in EXCLUDED_DIRS for part in path.parts[:-1]):
        return None
    name = path.name.lower()
    if name.endswith(('.min.js', '.min.css', '.d.ts', '.g.cs', '.generated.cs', '.designer.cs', '_pb2.py')):
        return None
    if name == 'dockerfile' or name.startswith('dockerfile.'):
        return 'Dockerfile'
    if name == 'cmakelists.txt':
        return 'CMake'
    if name == 'makefile':
        return 'Makefile'
    if path.suffix.lower() == '.ipynb':
        return 'Notebook'
    return EXTENSIONS.get(path.suffix.lower())


def notebook_counts(stream):
    notebook = json.load(stream)
    metadata = notebook.get('metadata', {})
    declared = metadata.get('language_info', {}).get('name') or metadata.get('kernelspec', {}).get('language', '')
    language = NOTEBOOK_LANGUAGES.get(declared.lower(), 'Notebook')
    count = 0
    for cell in notebook.get('cells', []):
        if cell.get('cell_type') == 'code':
            source = cell.get('source', [])
            source = source if isinstance(source, str) else ''.join(source)
            count += sum(bool(line.strip()) for line in source.splitlines())
    return Counter({language: count}) if count else Counter()


def count_archive(stream):
    counts = Counter()
    with tarfile.open(fileobj=stream, mode='r|gz') as archive:
        for member in archive:
            if not member.isfile() or '/' not in member.name:
                continue
            path = member.name.split('/', 1)[1]
            language = classify(path)
            if not language:
                continue
            source = archive.extractfile(member)
            if language == 'Notebook':
                counts.update(notebook_counts(source))
                continue
            # Peek at the prefix without loading large HTML/source files into memory.
            prefix = source.read(4096)
            utf16 = prefix.startswith((b'\xff\xfe', b'\xfe\xff'))
            if b'\0' in prefix and not utf16:
                continue
            lower = prefix.lower()
            if b'<auto-generated' in lower or (b'code generated' in lower and b'do not edit' in lower):
                continue
            if utf16:
                encoding = 'utf-16'
            else:
                encoding = 'utf-8-sig'
            # The buffered wrapper joins the prefix to the remaining streamed bytes.
            reader = io.TextIOWrapper(io.BufferedReader(PrefixedReader(prefix, source)), encoding=encoding, errors='replace')
            counts[language] += sum(bool(line.strip()) for line in reader)
    return Counter({name: count for name, count in counts.items() if count})


class PrefixedReader(io.RawIOBase):
    def __init__(self, prefix, stream):
        self.prefix = io.BytesIO(prefix)
        self.stream = stream

    def readable(self):
        return True

    def readinto(self, buffer):
        data = self.prefix.read(len(buffer))
        if not data:
            data = self.stream.read(len(buffer))
        buffer[:len(data)] = data
        return len(data)


def repository_lines(owner, repo, token):
    name = quote(repo['name'], safe='')
    ref = quote(repo['default_branch'], safe='')
    headers = {'Accept': 'application/vnd.github+json', 'User-Agent': 'profile-source-lines'}
    if token:
        headers['Authorization'] = f'Bearer {token}'
    request = Request(f'https://api.github.com/repos/{owner}/{name}/tarball/{ref}', headers=headers)
    try:
        with urlopen(request, timeout=120) as response:
            return count_archive(response)
    except HTTPError as error:
        if error.code == 404 and repo.get('size') == 0:
            # Size is rounded in metadata: a tiny repository may still contain code.
            # Only an explicit empty-repository response is safe to count as zero.
            tree = Request(f'https://api.github.com/repos/{owner}/{name}/git/trees/{ref}', headers=headers)
            try:
                with urlopen(tree, timeout=30) as response:
                    response.read()
            except HTTPError as tree_error:
                if tree_error.code == 409:
                    return Counter()
            raise error
        raise
    except (tarfile.TarError, json.JSONDecodeError, UnicodeError, OSError) as error:
        # Never include private file paths, source text or signed URLs in logs.
        if isinstance(error, (HTTPError, URLError)):
            raise
        raise ValueError('Unable to count a source archive; previous statistics preserved.') from None
